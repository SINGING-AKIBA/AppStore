/**
 * 生成 MP-WEIXIN 页面级主题 CSS
 * 注入到 page 元素，使 CSS 变量对所有子元素生效
 */
export function getMpThemeStyle(mode: ThemeMode): string {
  const vars = themeCssVars[mode]
  const cssText = Object.entries(vars)
    .map(([key, value]) => `${key}:${value}`)
    .join(';')
  return `page{${cssText}}`
}
