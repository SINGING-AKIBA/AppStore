#!/usr/bin/env node
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));

interface EntityInfo {
  className: string;
  filePath: string;
}

function scanEntities(modelDir: string): EntityInfo[] {
  const files = readdirSync(modelDir).filter((f) => f.endsWith(".ts") && f !== "Base.ts");
  const entities: EntityInfo[] = [];

  for (const file of files) {
    const filePath = resolve(modelDir, file);
    const content = readFileSync(filePath, "utf-8");

    // 检查文件是否包含 @Entity( 装饰器
    if (!/^\s*@Entity\s*\(/m.test(content)) continue;

    // 提取 export class ClassName
    const match = content.match(/^export\s+(abstract\s+)?class\s+(\w+)/m);
    if (!match) continue;

    entities.push({
      className: match[2],
      filePath,
    });
  }

  // 按类名排序，保证生成顺序稳定
  entities.sort((a, b) => a.className.localeCompare(b.className));
  return entities;
}

function generateEntitiesCode(entities: EntityInfo[], outputFile: string): string {
  const lines: string[] = [];
  lines.push("// Auto-generated by entity-scanner - do not modify manually");
  lines.push("// Run: pnpm --filter entity-scanner start");
  lines.push("");

  for (const entity of entities) {
    // 计算从 src/ 到 model 文件的相对路径
    const rel = relative(dirname(outputFile), entity.filePath).replace(/\\/g, "/").replace(/\.ts$/, "");
    lines.push(`import { ${entity.className} } from "${rel}";`);
  }

  lines.push("");
  lines.push("const entities = [");
  for (const entity of entities) {
    lines.push(`  ${entity.className},`);
  }
  lines.push("];");
  lines.push("");
  lines.push("export default entities;");
  lines.push("");

  return lines.join("\n");
}

function main() {
  // 从命令行参数获取项目根目录，默认为仓库根目录
  const projectRoot = process.argv[2]
    ? resolve(process.argv[2])
    : resolve(__dirname, "../../..");
  const modelDir = resolve(projectRoot, "src/app/common/model");
  const outputFile = resolve(projectRoot, "src/entities.ts");
  const entities = scanEntities(modelDir);
  const code = generateEntitiesCode(entities, outputFile);
  writeFileSync(outputFile, code, "utf-8");
}

main();